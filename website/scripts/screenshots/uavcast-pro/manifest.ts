/**
 * UAVcast-Pro screenshot manifest.
 *
 * Ids follow the docs contract: `uavcast-pro/<screen>[--<state>]`. A plain
 * `<screen>` id is the whole 1440×900 window; `--full` is the same page grown to
 * its full height; any other state is a focused crop or an opened control.
 *
 * Use `t:<ns>:<key>` for any text so the manifest works in every UI language.
 * Read-only rule: actions may only open/expand/switch tabs, never change settings.
 */
